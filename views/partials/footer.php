    <script>
    // Tunggu sampai semua konten halaman dimuat
    document.addEventListener('DOMContentLoaded', function () {

        // 1. Pilih semua elemen yang dibutuhkan
        const sections = document.querySelectorAll('section[id]'); // Semua section yang punya ID
        const navLinks = document.querySelectorAll('#main-nav a.nav-link'); // Semua link di navbar

        // Fungsi untuk menghapus class aktif dari semua link
        const removeAllActiveClasses = () => {
            navLinks.forEach(link => {
                link.classList.remove('text-rose-600', 'font-bold'); // Hapus class aktif
            });
        };

        // 2. Buat Intersection Observer
        const observer = new IntersectionObserver((entries) => {
            entries.forEach(entry => {
                // Jika section terlihat di layar (isIntersecting)
                if (entry.isIntersecting) {
                    // Dapatkan ID dari section yang terlihat
                    const sectionId = entry.target.id;
                    
                    // Hapus dulu semua class aktif yang mungkin ada
                    removeAllActiveClasses();

                    // Cari link yang cocok dengan sectionId
                    const activeLink = document.querySelector(`#main-nav a[data-target-id="${sectionId}"]`);
                    
                    if (activeLink) {
                        // Tambahkan class aktif ke link yang cocok
                        activeLink.classList.add('text-rose-600', 'font-bold');
                    }
                }
            });
        }, {
            threshold: 0.5 // Section dianggap aktif jika 50% terlihat di layar
        });

        // 3. Amati setiap section
        sections.forEach(section => {
            observer.observe(section);
        });
    });
</script>
